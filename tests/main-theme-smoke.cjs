 await until('!!document.querySelector("[data-testid=theme-system]")')
 for(const theme of ['light','dark','system']){
  await click('[data-testid=theme-'+theme+']')
  await until('document.querySelector("[data-testid=theme-'+theme+']").getAttribute("aria-checked")==="true"')
  assert.equal(JSON.parse(fs.readFileSync(path.join(app.getPath('userData'),'appearance.json'))).mode,theme)
 }
 nativeTheme.themeSource='dark';await until('document.documentElement.dataset.mainTheme==="dark"')
