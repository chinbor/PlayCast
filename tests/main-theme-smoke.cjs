 for(const [i,type] of ['comment','like','enter','follow','gift'].entries())fixture.emit({id:'theme-'+i,type,userId:'theme-user-'+i,userName:'主题测试观众',text:'一起冲向新的小目标！',count:2,giftId:'test',giftName:'小心心'})
