 await until('!!document.querySelector("[data-testid=tab-messages]")');await product.action('connect','123456')
 await capture('dark-gameplay-setup.png')
 await product.action('configureChallenge',{metricId:'champion-kills',target:20,rules:{likesEnabled:true,likeEvery:100,followEnabled:true,follow:1,commentsEnabled:true,commentKeywords:['加油'],gifts:[]}})
