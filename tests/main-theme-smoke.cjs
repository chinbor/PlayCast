 nativeTheme.themeSource='light';await wait(80);assert.equal(await run('document.documentElement.dataset.mainTheme'),'dark','Manual dark ignores a light OS')
 await run('document.querySelector("dialog .modal-header button").click()')
 await product.action('overlay');await product.action('messageOverlay')
 const find=hash=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('#'+hash))
 const exec=(hash,code)=>find(hash).webContents.executeJavaScript(code)
 for(const hash of ['overlay','messages-overlay'])await exec(hash,'document.querySelector("[data-testid=display-settings]").click()')
 for(const hash of ['challenge-settings','messages-settings']){
  for(let i=0;i<60;i++){
   if(find(hash)&&await exec(hash,'!!document.querySelector(".display-config")'))break
   await wait(50)
  }
  assert.equal(await exec(hash,'!!document.querySelector(".display-config")'),true,'Wait for the actual settings UI before comparing its colors')
 }
 const states=[]
 for(const hash of ['overlay','messages-overlay','challenge-settings','messages-settings']){
  const code='JSON.stringify({theme:document.documentElement.dataset.mainTheme,bg:getComputedStyle(document.body).backgroundColor,fg:getComputedStyle(document.body).color,surface:[...document.querySelectorAll(".broadcast-window,.message-display,.display-config")].map(e=>[getComputedStyle(e).backgroundColor,getComputedStyle(e).color])})'
  const before=await exec(hash,code);assert.equal(JSON.parse(before).theme,undefined)
  states.push({hash,code,before})
 }
 await run('window.liveTool.setAppearance("light")');await until('document.documentElement.dataset.mainTheme==="light"')
 for(const {hash,code,before} of states)assert.equal(await exec(hash,code),before,'Main theme must not change '+hash)
 for(const {hash} of states.reverse())find(hash).destroy()
 await capture('light-challenge.png')
 await run('window.liveTool.setAppearance("dark")');await until('document.documentElement.dataset.mainTheme==="dark"')
 main.webContents.reload()
 await until('!!document.querySelector("[data-testid=completed-value]")')
 assert.equal(await run('window.liveTool.initialAppearance.mode'),'dark');assert.equal(await run('document.documentElement.dataset.mainTheme'),'dark')
